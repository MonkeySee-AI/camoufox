async def AsyncNewBrowser(
    playwright: Playwright,
    *,
    headless: bool | Literal['virtual'] | None = None,
    from_options: dict[str, Any] | None = None,
    persistent_context: bool = False,
    debug: bool | None = None,
    **kwargs,
) -> Browser | BrowserContext:
    """
    Launches a new browser instance for Rotunda given a set of launch options.

    Parameters:
        from_options (Dict[str, Any]):
            A set of launch options generated by `launch_options()` to use
        persistent_context (bool):
            Whether to use a persistent context.
        **kwargs:
            All other keyword arugments passed to `launch_options()`.
    """
    if headless == 'virtual':
        virtual_display = VirtualDisplay(debug=debug)
        kwargs['virtual_display'] = virtual_display.get()
        headless = False
    else:
        virtual_display = None

    if not from_options:
        from_options = await asyncio.get_event_loop().run_in_executor(
            None,
            partial(launch_options, headless=headless, debug=debug, **kwargs),
        )
    assert from_options is not None

    # Persistent context
    if persistent_context:
        context_options = persistent_context_options(from_options)
        context = await playwright.firefox.launch_persistent_context("", **context_options)
        attach_debug_metadata(context, context_options)
        return await async_attach_vd(context, virtual_display)

    # Browser
    browser = await playwright.firefox.launch(**from_options)
    attach_debug_metadata(browser, from_options)
    return await async_attach_vd(browser, virtual_display)


def _proxy_url_with_creds(proxy: dict[str, str]) -> str:
    """Builds a proxy URL string with embedded credentials."""
    parsed = urlparse(proxy.get("server", ""))
    user = proxy.get("username", "")
    pwd = proxy.get("password", "")
    if user and pwd:
        return f"{parsed.scheme}://{user}:{pwd}@{parsed.netloc}"
    return proxy.get("server", "")


async def _resolve_proxy_geo(proxy: dict[str, str]) -> dict[str, str | None]:
    """Queries ip-api.com through the proxy for the exit IP and timezone."""
    proxy_url = _proxy_url_with_creds(proxy)

    def _fetch() -> dict[str, str | None]:
        handler = urllib.request.ProxyHandler({"http": proxy_url, "https": proxy_url})
        opener = urllib.request.build_opener(handler)
        try:
            with opener.open("http://ip-api.com/json?fields=query,timezone", timeout=10) as resp:
                data = _json.loads(resp.read())
                return {"ip": data.get("query") or None, "timezone": data.get("timezone") or None}
        except Exception:
            return {"ip": None, "timezone": None}

    return await asyncio.get_event_loop().run_in_executor(None, _fetch)


async def AsyncNewContext(
    browser: Browser,
    *,
    fingerprint: Fingerprint | None = None,
    preset: dict[str, Any] | None = None,
    os: str | None = None,
    ff_version: str | None = None,
    webrtc_ip: str | None = None,
    proxy: dict[str, str] | None = None,
    geolocation: dict[str, float] | None = None,
    debug: bool | None = None,
    **context_kwargs: Any,
) -> BrowserContext:
    """
    Creates a new browser context with a unique fingerprint identity.

    Each context gets its own host-compatible Firefox fingerprint identity.
    BrowserForge supplies the navigator/screen skeleton, while fonts and
    voices are sampled directly from the real host inventory. GPU-facing
    values stay real. All values are applied via addInitScript so they
    self-destruct before page scripts can detect them.

    Parameters:
        browser: A Browser instance from AsyncNewBrowser or AsyncRotunda.
        fingerprint: A BrowserForge fingerprint to compile directly. Use this
            when you need the browser launch and the page context to share the
            same navigator and geometry skeleton.
        preset: A specific fingerprint preset dict to compile. If None,
            BrowserForge generates the fingerprint skeleton.
        os: Target OS for BrowserForge/preset sampling. The default
            host-compatible path currently supports only the real current host OS.
        ff_version: Firefox version string for UA patching.
        webrtc_ip: IPv4 address to spoof for WebRTC ICE candidates.
        proxy: Per-context proxy (Playwright format: {"server": "...", "username": "...", "password": "..."}).
        geolocation: Per-context geolocation ({"latitude": float, "longitude": float}).
        debug: When True, print fingerprint generation diagnostics.
        **context_kwargs: Additional Playwright new_context() options.
    """
    # Auto-derive WebRTC IP and timezone from proxy's exit IP when not explicitly provided
    if proxy and (not webrtc_ip or "timezone_id" not in context_kwargs):
        geo = await _resolve_proxy_geo(proxy)
        if not webrtc_ip:
            webrtc_ip = geo["ip"]
        if "timezone_id" not in context_kwargs and geo["timezone"]:
            context_kwargs["timezone_id"] = geo["timezone"]

    if ff_version is None:
        ff_version = _derive_browser_major_version(browser)

    fp = await asyncio.get_event_loop().run_in_executor(
        None,
        lambda: generate_context_fingerprint(
            fingerprint=fingerprint,
            preset=preset,
            os=os,
            ff_version=ff_version,
            webrtc_ip=webrtc_ip,
            debug=bool(debug),
        ),
    )

    # Merge generated context options with user overrides (user wins)
    opts: dict[str, Any] = {**fp['context_options'], **context_kwargs}
    if proxy:
        opts['proxy'] = proxy
    if geolocation:
        opts['geolocation'] = geolocation
        opts.setdefault('permissions', ['geolocation'])

    context = await browser.new_context(**opts)
    await context.add_init_script(fp['init_script'])
    await install_async_context_debug_dump(
        context,
        browser=browser,
        fingerprint_payload=fp,
        context_options=opts,
    )
    return context
